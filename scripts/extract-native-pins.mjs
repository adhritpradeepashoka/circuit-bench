// Pin geometry for the @wokwi/elements parts whose pinInfo is computed (so extract-pins.mjs can't just read an array):
// instantiate the real elements in jsdom and read what they report. Run with: npm run extract-native-pins
import { JSDOM } from 'jsdom';
import { build } from 'esbuild';
import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const version = JSON.parse(readFileSync(join(root, 'node_modules/@wokwi/elements/package.json'), 'utf8')).version;
const entry = join(root, '.tmp-native-pins.js');
writeFileSync(entry, "import '@wokwi/elements';");
const out = await build({ entryPoints: [entry], bundle: true, write: false, format: 'iife', platform: 'browser' });
rmSync(entry);
const dom = new JSDOM('<!doctype html><body></body>', { runScripts: 'outside-only', pretendToBeVisual: true });
dom.window.eval(out.outputFiles[0].text);

const TAGS = ['wokwi-servo', 'wokwi-hc-sr04', 'wokwi-ky-040', 'wokwi-buzzer', 'wokwi-led-bar-graph', 'wokwi-ks2e-m-dc5', 'wokwi-tilt-switch', 'wokwi-small-sound-sensor', 'wokwi-big-sound-sensor', 'wokwi-slide-potentiometer'];
const body = TAGS.map(tag => {
  const pins = dom.window.document.createElement(tag).pinInfo || [];
  if (!pins.length) throw new Error(`${tag}: no pinInfo`);
  return ` '${tag}': [\n${pins.map(p => `  ${JSON.stringify({ name: p.name, x: +(+p.x).toFixed(3), y: +(+p.y).toFixed(3) })},`).join('\n')}\n ],`;
}).join('\n');
writeFileSync(join(root, 'src/core/pins.native.generated.js'), `// GENERATED by scripts/extract-native-pins.mjs from @wokwi/elements@${version}. Do not edit.\nexport const WOKWI_NATIVE_PINS = {\n${body}\n};\n`);
console.log('native pins:', TAGS.length);
