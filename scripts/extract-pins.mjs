// Reads pin geometry straight out of the installed @wokwi/elements sources so the
// editor's snapping/wiring uses the *library's* coordinates (CSS px, origin = top-left
// of the element). Run with: npm run extract-pins
// (At runtime main.js re-checks these tables against the live elements and warns on drift.)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'node_modules/@wokwi/elements/dist/esm');
const version = JSON.parse(readFileSync(join(root, 'node_modules/@wokwi/elements/package.json'), 'utf8')).version;
const read = f => readFileSync(join(dir, f), 'utf8');

// Elements whose pinInfo is a static array literal in the constructor.
const files = {
  'wokwi-arduino-uno': 'arduino-uno-element.js',
  'wokwi-resistor': 'resistor-element.js',
  'wokwi-pushbutton': 'pushbutton-element.js',
  'wokwi-rgb-led': 'rgb-led-element.js',
  'wokwi-slide-switch': 'slide-switch-element.js',
  'wokwi-pir-motion-sensor': 'pir-motion-sensor-element.js',
  'wokwi-potentiometer': 'potentiometer-element.js',
  'wokwi-photoresistor-sensor': 'photoresistor-sensor-element.js',
  'wokwi-ntc-temperature-sensor': 'ntc-temperature-sensor-element.js',
  'wokwi-mpu6050': 'mpu6050-element.js',
  'wokwi-ssd1306': 'ssd1306-element.js',
};
const out = {};
for (const [tag, file] of Object.entries(files)) {
  const src = read(file);
  const start = src.indexOf('this.pinInfo = [');
  const block = src.slice(start, src.indexOf('];', start));
  const starts = [...block.matchAll(/name:\s*'([^']+)'/g)];          // tolerant: key order differs; signals may nest braces
  out[tag] = starts.map((m, i) => {
    const chunk = block.slice(m.index, i + 1 < starts.length ? starts[i + 1].index : undefined);
    const x = /\bx:\s*([\d.]+)/.exec(chunk)?.[1], y = /\by:\s*([\d.]+)/.exec(chunk)?.[1];
    if (x === undefined || y === undefined) throw new Error(`${tag}: cannot read pin ${m[1]}`);
    return { name: m[1], x: +x, y: +y };
  });
}

// LED exposes pinInfo through a getter that depends on `flip`; default (flip = false):
const led = read('led-element.js');
const ax = /const anodeX = this\.flip \? \d+ : (\d+);/.exec(led)[1];
const cx = /const cathodeX = this\.flip \? \d+ : (\d+);/.exec(led)[1];
const ly = /name: 'A', x: anodeX, y: (\d+)/.exec(led)[1];
out['wokwi-led'] = [{ name: 'A', x: +ax, y: +ly }, { name: 'C', x: +cx, y: +ly }];

// 7-segment (1 digit, pins on top): the getter computes positions — reproduce its formula from the same constants.
{
  const src = read('7segment-element.js');
  const mm = +/mmToPix\s*=\s*([\d.]+)/.exec(read('utils/units.js'))?.[1] || 96 / 25.4;
  const startXk = /startX:\s*\((\d+(?:\.\d+)?)\s*\*\s*digits\s*-\s*cols\s*\*\s*(\d+(?:\.\d+)?)\)\s*\/\s*2/.exec(src);
  const bottom = +/bottomY:\s*this\.pins === 'extend' \? \d+ : (\d+)/.exec(src)[1];
  const digits = 1, cols = 5, startX = (+startXk[1] * digits - cols * +startXk[2]) / 2;
  const pinXY = n => {
    const col = (n - 1) % cols, row = 1 - Math.floor((n - 1) / cols);
    const x = startX + 1.27 + (row ? col : cols - col - 1) * 2.54, y = row ? bottom + 1 : 1;
    return { x: +(x * mm).toFixed(3), y: +(y * mm).toFixed(3) };
  };
  const one = /case 1:\s*default:[\s\S]*?return \[([\s\S]*?)\];/.exec(src)[1];
  out['wokwi-7segment'] = [...one.matchAll(/name: '([^']+)', \.\.\.pinXY\((\d+)\)/g)].map(m => ({ name: m[1], ...pinXY(+m[2]) }));
  if (out['wokwi-7segment'].length !== 10) throw new Error('7-segment pin table not parsed');
}

const body = Object.entries(out)
  .map(([k, v]) => ` '${k}': [\n${v.map(p => `  ${JSON.stringify(p)},`).join('\n')}\n ],`)
  .join('\n');
const text = `// GENERATED by scripts/extract-pins.mjs from @wokwi/elements@${version}. Do not edit.\n` +
  `export const WOKWI_ELEMENTS_VERSION = '${version}';\nexport const WOKWI_PINS = {\n${body}\n};\n`;
writeFileSync(join(root, 'src/core/pins.generated.js'), text);
console.log('pins:', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
