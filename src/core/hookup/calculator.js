// A four-function calculator for a 4×4 keypad and an OLED (or 16×2 LCD). The planner has already wired the parts; this only writes
// the sketch from the pins it chose. Keys: 0-9 digits, A + , B − , C × , D ÷ , # equals, * clear. Pure and DOM-free.

const q = s => `'${s}'`;

/** @param {{rows:number[]|string[], cols:number[]|string[], map:string[]}} kp  @param {'oled'|'lcd'} screen  @param {{includes:string[], globals:string[], setup:string[]}} sink */
export function calculatorSketch(kp, screen, sink, head = []) {
  const keys = kp.map.map(r => `{${[...r].map(q).join(', ')}}`).join(', ');
  const R = kp.rows.length, C = kp.cols.length;
  const draw = screen === 'oled' ? [
    'display.clearDisplay();',
    'display.setTextSize(1);',
    'display.setCursor(0, 0);',
    'display.print(top);',
    'display.setTextSize(2);',
    'display.setCursor(0, 30);',
    'display.print(big);',
    'display.display();',
  ] : [
    'lcd.clear();',
    'lcd.setCursor(0, 0);',
    'lcd.print(top);',
    'lcd.setCursor(0, 1);',
    'lcd.print(big);',
  ];
  const lines = [
    ...head.map(h => `// ${h}`),
    '// Keys: 0-9 digits   A = +   B = -   C = x   D = /   # = equals   * = clear',
    '',
    ...sink.includes.map(i => `#include <${i}>`),
    '',
    ...sink.globals,
    '',
    `const char KEYS[${R}][${C}] = {${keys}};`,
    `const int ROW_PINS[] = {${kp.rows.join(', ')}};`,
    `const int COL_PINS[] = {${kp.cols.join(', ')}};`,
    '',
    'String entry = "";        // the number being typed',
    'double acc = 0;           // the running total',
    'char pending = 0;         // the operator waiting for its second number',
    'bool typed = false;       // has a digit been typed since the last operator?',
    'bool failed = false;      // divided by zero',
    'char lastKey = 0;',
    '',
    'String format(double v) {',
    '  if (failed) return "Error";',
    '  if (fabs(v) < 1000000000.0 && v == (long)v) return String((long)v);',
    '  String s = String(v, 4);',
    '  while (s.endsWith("0")) s.remove(s.length() - 1);',
    '  if (s.endsWith(".")) s.remove(s.length() - 1);',
    '  return s;',
    '}',
    '',
    'void draw() {',
    '  String top = failed ? "" : (pending ? format(acc) + " " + String(pending) : "");',
    '  String big = typed ? entry : format(acc);',
    '  Serial.println(big);                // also visible in the Serial Monitor',
    ...draw.map(l => `  ${l}`),
    '}',
    '',
    'void calculate() {',
    '  double v = entry.toDouble();',
    '  if (!pending) acc = v;',
    '  else if (pending == \'+\') acc += v;',
    '  else if (pending == \'-\') acc -= v;',
    '  else if (pending == \'x\') acc *= v;',
    '  else if (v == 0) failed = true;',
    '  else acc /= v;',
    '  entry = "";',
    '}',
    '',
    'void press(char k) {',
    '  if (failed && k != \'*\') return;',
    '  if (k >= \'0\' && k <= \'9\') {',
    '    if (!typed) { entry = ""; typed = true; }',
    '    if (entry.length() < 9) entry += k;',
    '  } else if (k == \'*\') {',
    '    entry = ""; acc = 0; pending = 0; typed = false; failed = false;',
    '  } else if (k == \'#\') {',
    '    if (typed) calculate();',
    '    pending = 0; typed = false;',
    '  } else if (k == \'A\' || k == \'B\' || k == \'C\' || k == \'D\') {',
    '    if (typed) calculate();',
    '    pending = (k == \'A\') ? \'+\' : (k == \'B\') ? \'-\' : (k == \'C\') ? \'x\' : \'/\';',
    '    typed = false;',
    '  }',
    '  draw();',
    '}',
    '',
    'char scanKeys() {',
    '  char key = 0;',
    `  for (int r = 0; r < ${R}; r++) {`,
    '    digitalWrite(ROW_PINS[r], LOW);',
    `    for (int c = 0; c < ${C}; c++) if (digitalRead(COL_PINS[c]) == LOW) key = KEYS[r][c];`,
    '    digitalWrite(ROW_PINS[r], HIGH);',
    '  }',
    '  return key;',
    '}',
    '',
    'void setup() {',
    `  for (int r = 0; r < ${R}; r++) { pinMode(ROW_PINS[r], OUTPUT); digitalWrite(ROW_PINS[r], HIGH); }`,
    `  for (int c = 0; c < ${C}; c++) pinMode(COL_PINS[c], INPUT_PULLUP);`,
    '  delay(50);                       // let the pull-ups settle before the first read',
    '  Serial.begin(9600);',
    ...sink.setup.map(l => `  ${l}`),
    '  draw();',
    '}',
    '',
    'void loop() {',
    '  char key = scanKeys();',
    '  if (key && key != lastKey) press(key);          // a new key went down',
    '  lastKey = key;',
    '  delay(30);',
    '}',
  ];
  return `${lines.join('\n')}\n`;
}
